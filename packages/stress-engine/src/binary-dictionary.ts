export interface StressDictionary {
    get(word: string): number | undefined;
    readonly size: number;
}

export function createBinaryDictionary(
    bytes: Buffer,
): StressDictionary {
    //
    // PASS 1: count lines
    //
    let count = 0;
    let start = 0;

    while (start < bytes.length) {
        count++;

        const newline = bytes.indexOf(10, start);

        if (newline === -1) {
            break;
        }

        start = newline + 1;
    }

    //
    // PASS 2: store line starts
    //
    const lineStarts = new Uint32Array(count);

    let lineIndex = 0;
    start = 0;

    while (start < bytes.length) {
        lineStarts[lineIndex++] = start;

        const newline = bytes.indexOf(10, start);

        if (newline === -1) {
            break;
        }

        start = newline + 1;
    }

    return {
        size: lineStarts.length,

        get(word: string): number | undefined {
            const target = Buffer.from(word, "utf8");

            let low = 0;
            let high = lineStarts.length - 1;

            while (low <= high) {
                const mid = (low + high) >> 1;

                const lineStart = lineStarts[mid];

                // Every line is generated by the build script and
                // is guaranteed to contain a tab character.
                const tab = bytes.indexOf(9, lineStart);

                const newline = bytes.indexOf(10, lineStart);

                const end =
                    newline === -1
                        ? bytes.length
                        : newline;

                const wordBytes = bytes.subarray(
                    lineStart,
                    tab,
                );

                const comparison = Buffer.compare(
                    target,
                    wordBytes,
                );

                if (comparison === 0) {
                    const value = bytes.toString(
                        "utf8",
                        tab + 1,
                        end,
                    );

                    return Number(value);
                }

                if (comparison < 0) {
                    high = mid - 1;
                } else {
                    low = mid + 1;
                }
            }

            return undefined;
        },
    };
}