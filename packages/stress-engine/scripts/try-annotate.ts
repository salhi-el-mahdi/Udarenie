import { loadDictionary } from "../src/dictionary/load-dictionary";
import { annotateText } from "../src/stress/annotate-text";

async function main() {
    const dictionary = await loadDictionary("data/generated/ru-stress.tsv");

    const text = `Привет, мир! Сегодня хорошая погода, и я решил немного прогуляться по городу. По дороге я встретил старого друга, которого не видел уже несколько лет.

Мы зашли в небольшое кафе, заказали кофе и долго разговаривали о работе, книгах и путешествиях. Потом он рассказал интересную историю о том, как однажды потерялся в незнакомом городе и случайно нашёл очень красивый парк.

Когда стало темнеть, мы попрощались и договорились встретиться снова на следующей неделе. Я вернулся домой, приготовил ужин и ещё некоторое время читал книгу перед сном.`;

    console.log(
        annotateText(text, dictionary)
    );
}

main();